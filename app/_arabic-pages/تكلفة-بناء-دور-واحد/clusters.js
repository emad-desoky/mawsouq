export function getClusterBySlug(slug) {
  return (
    leadClusters.find((cluster) => cluster.slug === slug) ||
    futureClusterBlogs.find((cluster) => cluster.slug === slug) ||
    null
  );
}

export function getSiblings(currentSlug, limit = 3) {
  const current = getClusterBySlug(currentSlug);
  const published = futureClusterBlogs
    .filter(
      (cluster) => cluster.isLive === true && cluster.slug !== currentSlug,
    )
    .sort((a, b) => a.priority - b.priority);

  const curated = (current?.relatedSlugs || [])
    .map((slug) => published.find((cluster) => cluster.slug === slug))
    .filter(Boolean);

  const fallback = published.filter(
    (cluster) => !curated.some((item) => item.slug === cluster.slug),
  );

  return [...curated, ...fallback].slice(0, limit);
}

export function getPublishedClusters() {
  return [...futureClusterBlogs, ...leadClusters]
    .filter((cluster) => cluster.isLive)
    .sort((a, b) => new Date(b.dateModified || b.datePublished) - new Date(a.dateModified || a.datePublished));
}

export function getAllBlogEntries() {
  return [
    {
      url: pillarUrl,
      lastModified: pillar.dateModified,
      changeFrequency: "weekly",
      priority: 0.95,
    },
    ...getPublishedClusters().map((cluster) => ({
      url: `${SITE_URL}/${encodeURIComponent(cluster.slug)}/`,
      lastModified: cluster.dateModified,
      changeFrequency: "monthly",
      priority: 0.78,
    })),
  ];
}
