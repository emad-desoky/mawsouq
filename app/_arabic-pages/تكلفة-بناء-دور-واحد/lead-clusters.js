export function getLeadClusterBySlug(slug) {
  return leadClusters.find((cluster) => cluster.slug === slug) || null;
}

export function getLeadSiblings(slug, limit = 4) {
  return leadClusters.filter((cluster) => cluster.slug !== slug).slice(0, limit);
}

export function getLeadBlogEntries() {
  return leadClusters.map((cluster) => ({
    slug: cluster.slug,
    title: cluster.title,
    description: cluster.excerpt,
    image: cluster.image,
    imageAlt: cluster.imageAlt,
    dateModified: cluster.dateModified,
  }));
}

