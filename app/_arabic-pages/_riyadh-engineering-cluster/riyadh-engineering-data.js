export function createRiyadhEngineeringMetadata(article) {
  const url = articleUrl(article);
  const imageUrl = `${SITE_URL}${article.hero}`;

  return {
    title: article.metaTitle,
    description: article.description,
    keywords: article.keywords,
    alternates: { canonical: url },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-snippet": -1,
        "max-image-preview": "large",
        "max-video-preview": -1,
      },
    },
    openGraph: {
      type: "article",
      title: article.metaTitle,
      description: article.description,
      url,
      siteName: "موسوق",
      locale: "ar_SA",
      publishedTime: `${article.datePublished}T12:00:00+03:00`,
      modifiedTime: `${article.dateModified}T12:00:00+03:00`,
      images: [{ url: imageUrl, width: 1200, height: 630, alt: article.heroAlt }],
    },
    twitter: {
      card: "summary_large_image",
      title: article.metaTitle,
      description: article.description,
      images: [imageUrl],
    },
  };
}

