export const allResthouseArticles = [pillar, ...clusters];
export const pillarUrl = `${SITE_URL}/${pillar.slug}/`;

export function getResthouseArticle(slug) {
  return allResthouseArticles.find((article) => article.slug === slug) || null;
}

export function getResthouseCluster(slug) {
  return clusters.find((cluster) => cluster.slug === slug) || null;
}

export function getResthouseSiblings(currentSlug, limit = 4) {
  return clusters.filter((cluster) => cluster.slug !== currentSlug).slice(0, limit);
}

export function getAllResthouseEntries() {
  return allResthouseArticles.map((article) => ({
    url: `${SITE_URL}/${article.slug}/`,
    lastModified: article.dateModified,
    changeFrequency: article.role === "pillar" ? "weekly" : "monthly",
    priority: article.role === "pillar" ? 0.95 : 0.82,
  }));
}
