export function getExistingLink(key) {
  const direct = strongExistingLinks.find((item) => item.href === `/${key}/`);
  if (direct) return direct;
  return strongExistingLinks.find((item) => item.title === key) || null;
}

const all = interiorClusterLinks.map((link) => ({
  ...link,
  ...interiorPricingArticles[link.slug],
  excerpt: interiorPricingArticles[link.slug]?.description || "",
  image: interiorPricingArticles[link.slug]?.hero || "",
  imageAlt: interiorPricingArticles[link.slug]?.heroAlt || "",
  keywords: [
    interiorPricingArticles[link.slug]?.primaryKeyword,
    `${interiorPricingArticles[link.slug]?.primaryKeyword} 2026`,
  ].filter(Boolean),
  datePublished: LAST_UPDATED,
  dateModified: LAST_UPDATED,
  readTime: "8–12 دقيقة",
}));

export const pillar = all[0];

// Every cluster article (live or not) for page lookups.
export const allClusters = all.slice(1);

// Only published clusters are linked from anywhere.
export const clusters = allClusters.filter((item) => item.live);

export const pillarUrl = pillar.href;

export function getAnyArticle(slug) {
  if (slug === pillar.slug) return pillar;
  return allClusters.find((item) => item.slug === slug) || null;
}

export function getClusterBySlug(slug) {
  return clusters.find((item) => item.slug === slug) || null;
}

export function getSiblings(currentSlug, limit = 3) {
  return clusters.filter((item) => item.slug !== currentSlug).slice(0, limit);
}

export function getAllBlogEntries() {
  return [pillar, ...clusters]
    .filter((item) => item.live)
    .map((item) => ({
      url: item.href,
      lastModified: item.dateModified || LAST_UPDATED,
    }));
}

// Paths that must stay out of the sitemap until their wave goes live.
export function getHiddenInteriorPricingPaths() {
  return allClusters.filter((item) => !item.live).map((item) => `/${item.slug}`);
}
