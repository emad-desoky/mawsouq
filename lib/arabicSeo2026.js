export function getArabicSeo2026Page(key) {
  const page = ARABIC_SEO_2026_PAGES[key];
  if (!page) throw new Error(`Unknown Arabic SEO 2026 page key: ${key}`);
  return page;
}

export function getArabicSeo2026Metadata(key) {
  const page = getArabicSeo2026Page(key);
  const canonical = `${SITE_URL}/${page.slug}/`;
  const image = `${SITE_URL}${page.heroImage}`;

  return {
    title: page.metaTitle,
    description: page.metaDescription,
    keywords: [page.primaryKeyword, page.title, page.category, "موسوق", "السعودية"],
    alternates: { canonical },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-image-preview": "large",
        "max-snippet": -1,
        "max-video-preview": -1,
      },
    },
    openGraph: {
      type: "article",
      locale: "ar_SA",
      siteName: "موسوق",
      url: canonical,
      title: page.metaTitle,
      description: page.metaDescription,
      images: [{ url: image, width: 1600, height: 900, alt: page.imageAlt }],
    },
    twitter: {
      card: "summary_large_image",
      title: page.metaTitle,
      description: page.metaDescription,
      images: [image],
    },
  };
}

export function getAllArabicSeo2026Entries() {
  return Object.values(ARABIC_SEO_2026_PAGES).map((page) => ({
    url: `${SITE_URL}/${page.slug}/`,
    lastModified: page.dateModified,
    changeFrequency: page.pageType === "pillar" || page.pageType === "local-commercial" ? "weekly" : "monthly",
    priority: page.pageType === "pillar" || page.pageType === "local-commercial" ? 0.95 : 0.86,
  }));
}

export function getArabicSeo2026BlogCards() {
  return Object.values(ARABIC_SEO_2026_PAGES).map((page) => ({
    slug: page.slug,
    title: page.title,
    excerpt: page.subtitle,
    category:
      page.category.includes("تكلفة") || page.slug.includes("تكلفة") || page.slug.includes("سعر")
        ? "تكاليف البناء"
        : "التصميم المعماري",
    image: page.heroImage,
  }));
}

